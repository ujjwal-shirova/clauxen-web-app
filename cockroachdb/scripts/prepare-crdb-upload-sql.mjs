#!/usr/bin/env node
/**
 * Regenerate cockroachdb/migrations/*.sql from supabase/migrations for manual
 * CockroachDB Cloud SQL Console upload (lexical filename order).
 *
 * Usage: node cockroachdb/scripts/prepare-crdb-upload-sql.mjs
 */

import {
  readFileSync,
  readdirSync,
  writeFileSync,
  mkdirSync,
  existsSync,
} from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { preprocessCrdbUploadSql } from "./crdb-sql-preprocess.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const SUPABASE_MIGRATIONS = join(REPO_ROOT, "supabase", "migrations");
const CRDB_MIGRATIONS = join(REPO_ROOT, "cockroachdb", "migrations");

const UPLOAD_HEADER = `-- =============================================================================
-- CockroachDB Cloud — manual SQL upload (Postgres integer semantics)
-- Unqualified INT / INTEGER in this session resolve to INT4 (like PostgreSQL).
-- Apply cockroachdb/bootstrap/crdb_supabase_shim.sql once before the first migration.
-- Generated by: node cockroachdb/scripts/prepare-crdb-upload-sql.mjs
-- =============================================================================
SET default_int_size = 4;

`;

const PRAGMAS_ONLY = `-- =============================================================================
-- Run this file first (or rely on SET default_int_size in each migration).
-- =============================================================================
SET default_int_size = 4;
`;

const NOOP_EXTREME_HARDENING = `${UPLOAD_HEADER}
-- CRDB upload: Supabase-only migration (HypoPg, pg_cron, extension-heavy tuning).
-- Omitted for CockroachDB; schema is unchanged by this placeholder.
SELECT 1 AS crdb_upload_noop;
`;

const MINIMAL_EXTENSION_CORRECTIONS = `${UPLOAD_HEADER}
-- CRDB upload: pg_net / pgmq extension install and privilege loops omitted.
CREATE SCHEMA IF NOT EXISTS pgmq;
`;

function stripUploadHeaderIfPresent(text) {
  const marker = "SET default_int_size = 4;";
  const idx = text.indexOf(marker);
  if (idx === -1) return text;
  const after = text.indexOf("\n", idx);
  if (after === -1) return text;
  return text.slice(after + 1).replace(/^\s*\n+/, "");
}

function main() {
  mkdirSync(CRDB_MIGRATIONS, { recursive: true });

  writeFileSync(
    join(CRDB_MIGRATIONS, "00000000000000_cockroach_upload_pragmas.sql"),
    `${PRAGMAS_ONLY}\n`,
    "utf8",
  );

  const names = readdirSync(SUPABASE_MIGRATIONS)
    .filter((f) => f.endsWith(".sql"))
    .sort();

  for (const name of names) {
    if (name === "00000000000000_cockroach_upload_pragmas.sql") continue;

    const srcPath = join(SUPABASE_MIGRATIONS, name);
    if (!existsSync(srcPath)) continue;

    let body = readFileSync(srcPath, "utf8");

    if (name === "20260508100000_supabase_extreme_performance_hardening.sql") {
      writeFileSync(
        join(CRDB_MIGRATIONS, name),
        NOOP_EXTREME_HARDENING,
        "utf8",
      );
      console.log(`Wrote ${name} (CRDB noop placeholder)`);
      continue;
    }

    if (name === "20260508103000_extension_schema_corrections.sql") {
      writeFileSync(
        join(CRDB_MIGRATIONS, name),
        MINIMAL_EXTENSION_CORRECTIONS,
        "utf8",
      );
      console.log(`Wrote ${name} (CRDB minimal placeholder)`);
      continue;
    }

    body = stripUploadHeaderIfPresent(body);
    const out = `${UPLOAD_HEADER}\n${preprocessCrdbUploadSql(body, name)}`;
    writeFileSync(join(CRDB_MIGRATIONS, name), out, "utf8");
    console.log(`Wrote ${name}`);
  }

  console.log(
    `\nDone. Upload order: crdb_supabase_shim.sql → 00000000000000_* → 20260506… in lexical order.`,
  );
}

main();
