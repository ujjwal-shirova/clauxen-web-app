function main() {
  mkdirSync(NATIVE_DIR, { recursive: true });

  writeFileSync(
    join(NATIVE_DIR, "001_pragmas.sql"),
    `${NATIVE_HEADER("__pragmas__", "001_pragmas.sql")}-- Session defaults for Postgres-like INTEGER (INT4).
`,
    "utf8",
  );

  const shimBody = readFileSync(SHIM, "utf8");
  writeFileSync(
    join(NATIVE_DIR, "002_bootstrap_shim.sql"),
    `${NATIVE_HEADER("__bootstrap__", "002_bootstrap_shim.sql")}${shimBody}\n`,
    "utf8",
  );

  const manifest = {
    version: 1,
    targetDatabase: "clauxen_main",
    generatedAt: new Date().toISOString(),
    files: ["001_pragmas.sql", "002_bootstrap_shim.sql"],
  };

  for (const [srcKey, nativeName] of ORDER.slice(2)) {
    if (srcKey === "__pragmas__" || srcKey === "__bootstrap__") continue;

    if (!existsSync(join(SUPABASE_DIR, srcKey))) {
      console.warn(`Skip missing ${srcKey}`);
      continue;
    }

    if (SKIP_AS_NOOP.has(srcKey)) {
      const body = srcKey.includes("extreme_performance")
        ? NOOP_EXTREME(nativeName)
        : `${NATIVE_HEADER(srcKey, nativeName)}-- Dynamic pg_policies rewrite omitted on CockroachDB.
SELECT 1 AS crdb_noop;
`;
      writeFileSync(join(NATIVE_DIR, nativeName), body, "utf8");
      manifest.files.push(nativeName);
      console.log(`Wrote ${nativeName} (noop)`);
      continue;
    }

    if (srcKey === "20260508103000_extension_schema_corrections.sql") {
      writeFileSync(
        join(NATIVE_DIR, nativeName),
        MINIMAL_EXT_CORRECTIONS(nativeName),
        "utf8",
      );
      manifest.files.push(nativeName);
      console.log(`Wrote ${nativeName} (minimal)`);
      continue;
    }

    let body = readFileSync(join(SUPABASE_DIR, srcKey), "utf8");
    body = preprocessCrdbUploadSql(body, srcKey);
    writeFileSync(
      join(NATIVE_DIR, nativeName),
      `${NATIVE_HEADER(srcKey, nativeName)}\n${body}\n`,
      "utf8",
    );
    manifest.files.push(nativeName);
    console.log(`Wrote ${nativeName} <- ${srcKey}`);
  }

  writeFileSync(
    join(NATIVE_DIR, "manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf8",
  );
  console.log(
    `\nGenerated ${manifest.files.length} files in cockroachdb/migrations-native/`,
  );
}

main();
